-- One-time setup. Run top to bottom in a Snowsight worksheet as a user with ACCOUNTADMIN.
-- Before running, replace:
--   <YOUR_USERNAME>        your Snowflake login name
--   <LOADER_PUBLIC_KEY>    contents of keys/loader_key.pub without the BEGIN/END lines
--   <DBT_PUBLIC_KEY>       contents of keys/dbt_key.pub without the BEGIN/END lines

-- 1. Roles (SECURITYADMIN owns roles, users and grants)
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Writes source data into RAW';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'Reads RAW, builds ANALYTICS with dbt';
CREATE ROLE IF NOT EXISTS REPORTER    COMMENT = 'Reads production models for dashboards';

GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

GRANT ROLE LOADER      TO USER <YOUR_USERNAME>;
GRANT ROLE TRANSFORMER TO USER <YOUR_USERNAME>;
GRANT ROLE REPORTER    TO USER <YOUR_USERNAME>;

-- 2. Warehouses and databases (SYSADMIN owns objects)
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LOADING_WH      WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORMING_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS REPORTING_WH    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RAW       COMMENT = 'Source data exactly as delivered';
CREATE DATABASE IF NOT EXISTS ANALYTICS COMMENT = 'dbt output: dev, ci and prod schemas';

CREATE SCHEMA IF NOT EXISTS RAW.STRIPE;
CREATE SCHEMA IF NOT EXISTS RAW.SEGMENT;
CREATE SCHEMA IF NOT EXISTS RAW.ECB;
CREATE SCHEMA IF NOT EXISTS RAW.GROUND_TRUTH;

-- 3. Loading objects
CREATE FILE FORMAT IF NOT EXISTS RAW.PUBLIC.JSONL      TYPE = JSON;
CREATE FILE FORMAT IF NOT EXISTS RAW.PUBLIC.CSV_HEADER TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';
CREATE STAGE IF NOT EXISTS RAW.PUBLIC.LANDING COMMENT = 'Landing files uploaded by ingestion/load.py';

-- 4. Raw tables: one VARIANT row per delivered record, plus load metadata
CREATE TABLE IF NOT EXISTS RAW.STRIPE.CUSTOMERS     (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.SUBSCRIPTIONS (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.INVOICES      (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.CHARGES       (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.REFUNDS       (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.PRODUCTS      (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.PRICES        (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.STRIPE.COUPONS       (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.SEGMENT.TRACKS       (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);
CREATE TABLE IF NOT EXISTS RAW.ECB.RATES            (RAW VARIANT, _FILE STRING, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_LTZ);

CREATE TABLE IF NOT EXISTS RAW.GROUND_TRUTH.MRR_MONTHLY (
    MONTH STRING, CUSTOMER_ID STRING, CURRENCY STRING,
    MRR NUMBER(12, 2), PREVIOUS_MRR NUMBER(12, 2), MOVEMENT STRING
) COMMENT = 'Simulator answer key. Only for reconciliation tests, never a model input.';

-- 5. Grants
USE ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE LOADING_WH      TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE TRANSFORMING_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE REPORTING_WH    TO ROLE REPORTER;

-- LOADER: write RAW
GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RAW TO ROLE LOADER;
GRANT SELECT, INSERT, DELETE ON ALL TABLES IN DATABASE RAW TO ROLE LOADER;
GRANT SELECT, INSERT, DELETE ON FUTURE TABLES IN DATABASE RAW TO ROLE LOADER;
GRANT READ, WRITE ON STAGE RAW.PUBLIC.LANDING TO ROLE LOADER;
GRANT USAGE ON FILE FORMAT RAW.PUBLIC.JSONL TO ROLE LOADER;
GRANT USAGE ON FILE FORMAT RAW.PUBLIC.CSV_HEADER TO ROLE LOADER;

-- TRANSFORMER: read RAW, create schemas in ANALYTICS
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS TO ROLE TRANSFORMER;

-- REPORTER: dbt grants SELECT on production models (phase 8 of the build guide)
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;

-- 6. Service users with key-pair authentication
CREATE USER IF NOT EXISTS LOADER_USER
    TYPE = SERVICE DEFAULT_ROLE = LOADER DEFAULT_WAREHOUSE = LOADING_WH
    RSA_PUBLIC_KEY = '<LOADER_PUBLIC_KEY>';
CREATE USER IF NOT EXISTS DBT_USER
    TYPE = SERVICE DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = TRANSFORMING_WH
    RSA_PUBLIC_KEY = '<DBT_PUBLIC_KEY>';
GRANT ROLE LOADER      TO USER LOADER_USER;
GRANT ROLE TRANSFORMER TO USER DBT_USER;

-- 7. Spend cap (resource monitors need ACCOUNTADMIN)
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS PORTFOLIO_MONITOR WITH
    CREDIT_QUOTA = 50 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY
             ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE LOADING_WH      SET RESOURCE_MONITOR = PORTFOLIO_MONITOR;
ALTER WAREHOUSE TRANSFORMING_WH SET RESOURCE_MONITOR = PORTFOLIO_MONITOR;
ALTER WAREHOUSE REPORTING_WH    SET RESOURCE_MONITOR = PORTFOLIO_MONITOR;

-- 8. Check
SHOW GRANTS TO ROLE LOADER;
SHOW GRANTS TO ROLE TRANSFORMER;
